"""Функции для расчёта основных статистик по списку словарей."""

from statistics import mean, median


def numeric_values(records: list, attribute: str) -> list:
    """
Собираем все числовые значения указанного поля.

Функция проходит по списку словарей и оставляет только
значения типа int или float. Пропуски, строки и логические
значения True и False в результат не попадают.

Это нужно, чтобы при расчёте статистик случайно не
учитывать некорректные значения. Например, если в поле
возраста встречается None, оно не должно влиять на среднее.

Args:
    records: Список словарей с данными.
    attribute: Название поля, из которого берём числа.

Returns:
    Список числовых значений указанного поля.
"""
    return [
        record[attribute]
        for record in records
        if type(record.get(attribute)) in (int, float)
    ]


def count_records(records: list) -> int:
    """
Теперь посчитаем количество записей в переданном списке.

Каждый элемент списка считается отдельной записью.
Функция не проверяет уникальность объектов и не удаляет
дубликаты, поэтому результат зависит от того, какие
данные были переданы на вход.

Args:
    records: Список записей, которые нужно посчитать.

Returns:
    Количество элементов списка. Если список пустой,
    возвращается 0.
"""
    return len(records)


def mean_value(records: list, attribute: str):
    """
Рассчитаем среднее арифметическое значений указанного поля.

Сначала функция получает все корректные числовые значения
через numeric_values. Затем считает их среднее.

Пропуски и нечисловые значения не участвуют в расчёте.
Например, при анализе возраста лауреатов среднее будет
считаться только по тем записям, где возраст представлен
числом.

Args:
    records: Список словарей с данными.
    attribute: Поле, для которого рассчитываем среднее.

Returns:
    Среднее арифметическое числовых значений.
    Если подходящих значений нет, возвращается None.
"""
    numbers = numeric_values(records, attribute)
    return mean(numbers) if numbers else None


def median_value(records: list, attribute: str):
    """
Найдем медиану числовых значений указанного поля.

Медиана показывает центральное значение распределения.
Если количество наблюдений нечётное, берётся центральное
значение, а если чётное, то берем среднее двух центральных.

Как и при расчёте среднего, пропуски и нечисловые
значения предварительно исключаются.

Args:
    records: Список словарей с данными.
    attribute: Поле, для которого ищем медиану.

Returns:
    Медиана числовых значений или None, если подходящих
    наблюдений нет.
"""
    numbers = numeric_values(records, attribute)
    return median(numbers) if numbers else None


def max_value(records: list, attribute: str):
    """
Найти максимальное числовое значение указанного поля.

Функция сначала отбирает только числовые значения,
а затем находит среди них наибольшее.

В проекте это используется, например, для определения
максимального возраста лауреата при получении первой
Нобелевской премии.

Args:
    records: Список словарей с данными.
    attribute: Поле, по которому ищем максимум.

Returns:
    Максимальное числовое значение или None, если
    в указанном поле нет подходящих значений.
"""
    numbers = numeric_values(records, attribute)
    return max(numbers) if numbers else None


def top_n(records: list, attribute: str, number: int = 5,
          reverse: bool = True) -> list:
    """
Выберем несколько записей с самыми большими или маленькими
значениями указанного числового поля.

Функция сначала исключает записи, в которых нужное поле
отсутствует или содержит нечисловое значение. Затем
сортирует оставшиеся записи и возвращает первые N.

По умолчанию сортировка идёт по убыванию. Если передать
reverse=False, можно получить записи с минимальными
значениями.

Args:
    records: Список словарей, которые нужно отсортировать.
    attribute: Числовое поле, по которому идёт сортировка.
    number: Сколько первых записей нужно вернуть.
    reverse: True — сортировка по убыванию,
        False — по возрастанию.

Returns:
    Список из не более чем N исходных словарей,
    отсортированных по выбранному полю.

Raises:
    ValueError: Если number отрицательный.
"""
    if number < 0:
        raise ValueError('Число записей не может быть отрицательным.')
    filled = [
        record for record in records
        if type(record.get(attribute)) in (int, float)
    ]
    return sorted(
        filled, key=lambda record: record[attribute], reverse=reverse,
    )[:number]
