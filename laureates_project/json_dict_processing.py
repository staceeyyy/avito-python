"""
Здесь запишем универсальные функции для обработки вложенных JSON-данных.

Данные Nobel Prize API содержат вложенные словари и списки, и чтобы не 
извлекать каждое поле вручную, используем подход с конфигурациями.

Конфигурация задаёт, какие поля нужно получить из исходного JSON, по 
какому пути они находятся и нужно ли дополнительно преобразовать их 
значения.

С помощью этого один и тот же механизм будем использовать для обработки 
людей, организаций и Нобелевских премий.
"""


def extract_nested_value(obj, keys):
    """
Здесь будем получать значение из вложенного словаря или списка по пути.

Путь задаётся последовательностью ключей. Функция проходит по ним один 
за другим, постепенно переходя на следующий уровень вложенности.

Если наш текущий объект это словарь, используется соответствующий ключ. 
Если это список, можно обратиться к элементу по его целочисленному 
индексу.

Если на каком-то шаге ключа нет, индекс выходит за границы списка или 
дальнейший переход невозможен, будем возвращать None. Это позволит нам 
обрабатывать JSON с пропущенными полями без возникновения KeyError или 
IndexError.

Args:
    obj: Исходный объект со вложенными данными.
    keys: Список ключей и индексов, определяющих путь 
    до нужного значения.

Returns:
    Найденное значение или None, если путь не существует.
    Если keys пустой, возвращается сам исходный объект.
"""
    for key in keys:
        if isinstance(obj, dict):
            obj = obj.get(key)
        elif isinstance(obj, list) and isinstance(key, int):
            if not 0 <= key < len(obj):
                return None
            obj = obj[key]
        else:
            return None
    return obj


def process_dictionary_with_config(dictionary: dict, config: dict) -> dict:
    """
Здесь будем преобразовать один словарь по заранее заданной конфигурации.

Функция создаёт новый словарь и заполняет его только теми полями, 
которые указаны в config.

Для каждого нового поля конфигурация задаёт путь к значению в исходном 
JSON. При необходимости можно дополнительно указать функцию 
преобразования, например int для перевода строкового ID в число или 
process_year для обработки даты.

Если правило задано обычным списком, значение просто извлекается по 
указанному пути. Если правило представляет собой кортеж, то его первый 
элемент - путь, а второй - это функция для обработки найденного 
значения.

Args:
    dictionary: Исходный словарь с данными.
    config: Словарь с правилами извлечения и преобразования
        полей.

Returns:
    Новый словарь с полями, которые указаны в конфигурации.
"""
    result = {}
    for attribute, rule in config.items():
        if isinstance(rule, tuple):
            keys, processor = rule
            value = extract_nested_value(dictionary, keys)
            result[attribute] = processor(value) if value is not None else None
        else:
            result[attribute] = extract_nested_value(dictionary, rule)
    return result


def process_list_of_dicts_with_config(list_of_dicts, config: dict) -> list:
    """
Теперь будем обрабатывать список словарей с помощью одной конфигурации.

Функция последовательно применяет process_dictionary_with_config к 
каждому элементу списка.

Это удобно, когда API возвращает сразу много объектов одинаковой 
структуры, например список Нобелевских премий. Вместо отдельной 
обработки каждого элемента можно использовать один общий набор правил.

Args:
    list_of_dicts: Список исходных словарей.
    config: Конфигурация извлечения и преобразования полей.

Returns:
    Новый список обработанных словарей.
    Если вместо списка передан None, возвращаем
    пустой список.
"""
    if list_of_dicts is None:
        return []
    return [
        process_dictionary_with_config(dictionary, config)
        for dictionary in list_of_dicts
    ]


def create_processor(config: dict, list_processor: bool = False):
    """
Создаем готовую функцию для обработки данных по конфигурации.

Функция принимает конфигурацию один раз и возвращает новую функцию,
которая уже использует эти правила.

Параметр list_processor определяет, с чем будет работать созданная 
функция: с одним словарём или со списком словарей.

Args:
    config: Правила извлечения и преобразования полей.
    list_processor: Если True, обработчик рассчитан на список.
        Если False, на один словарь.

Returns:
    Функция processor, которая принимает данные
    и преобразует их с помощью заданной конфигурации.
"""
    def processor(records):
        """
Применяем сохранённую конфигурацию к переданным данным.

В зависимости от параметра list_processor, заданного при создании 
обработчика, функция обрабатывает один словарь или целый список 
словарей.

Returns:
    Словарь или список словарей с преобразованными полями.
"""
        if list_processor:
            return process_list_of_dicts_with_config(records, config)
        return process_dictionary_with_config(records, config)

    return processor
