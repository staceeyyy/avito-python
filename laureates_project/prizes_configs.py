"""
Конфигурация для обработки информации о Нобелевских премиях.

В исходном JSON у каждого лауреата есть список nobelPrizes, и каждый 
элемент этого списка содержит сведения об отдельном награждении.

Конфигурация позволяет извлечь год, категорию, статус,
денежную сумму премии и текст мотивации её вручения.
"""

from core import create_processor

CONFIG_PRIZE = {
    'prize_amount': ['prizeAmount'],
    'prize_amount_adjusted': ['prizeAmountAdjusted'],
    'award_year': (['awardYear'], int),
    'category_en': ['category', 'en'],
    'prize_status': ['prizeStatus'],
    'motivation': ['motivation', 'en'],
}


def prize_processor():
    """
Здесь пишу обработчик списка Нобелевских премий.

Функция использует CONFIG_PRIZE, в котором описаны правила извлечения 
нужных полей из данных о награждении.

Т.к. один лауреат может получить несколько премий, обработчик рассчитан 
именно на список словарей.

Он позволяет преобразовать все награды одного лауреата в единый формат,
который дальше удобно использовать для группировок и статистического 
анализа.

Returns:
    Функция для преобразования списка наград по конфигурации 
    CONFIG_PRIZE.
"""
    return create_processor(CONFIG_PRIZE, list_processor=True)
